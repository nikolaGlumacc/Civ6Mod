-- NUCLEAR: for every MapLeaders row map, also place Serbia at Macedon plot if that map has one
INSERT OR IGNORE INTO MapStartPositions (Map, Plot, Type, Value)
SELECT m.Map, p.Plot, 'LEADER', 'LEADER_STR_SERBIA_STEFAN_UROS_IV_DUSAN_THE_MIGHTY_NEMANJIC'
FROM MapLeaders m
JOIN MapStartPositions p ON p.Map = m.Map AND p.Type='CIVILIZATION' AND p.Value='CIVILIZATION_MACEDON'
WHERE m.LeaderType = 'LEADER_STR_SERBIA_STEFAN_UROS_IV_DUSAN_THE_MIGHTY_NEMANJIC';
