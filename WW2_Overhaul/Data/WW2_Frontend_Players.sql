SELECT DISTINCT Map, 'LEADER_STR_SERBIA_STEFAN_UROS_IV_DUSAN_THE_MIGHTY_NEMANJIC'
FROM MapLeaders
WHERE LeaderType IN (
  'LEADER_ALEXANDER',
  'LEADER_MATTHIAS_CORVINUS',
  'LEADER_PERICLES',
  'LEADER_GORGO',
  'LEADER_TRAJAN',
