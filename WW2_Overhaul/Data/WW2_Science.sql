-- Hard science: nukes stay late-war
UPDATE GlobalParameters SET Value = 10 WHERE Name = 'SCIENCE_PERCENTAGE_YIELD_PER_POP';

UPDATE Building_YieldChanges
SET YieldChange = CASE WHEN YieldChange > 2 THEN YieldChange - 2 ELSE YieldChange END
WHERE YieldType = 'YIELD_SCIENCE' AND YieldChange > 2;

UPDATE Technologies SET Cost = Cost * 3
WHERE TechnologyType IN (
  'TECH_NUCLEAR_FISSION', 'TECH_NUCLEAR_FUSION',
  'TECH_NANOTECHNOLOGY', 'TECH_SMART_MATERIALS', 'TECH_PREDICTIVE_SYSTEMS'
);

UPDATE Technologies SET Cost = Cost * 2
WHERE TechnologyType IN (
  'TECH_ROCKETRY', 'TECH_COMPUTERS', 'TECH_SATELLITES',
  'TECH_GUIDANCE_SYSTEMS', 'TECH_LASERS', 'TECH_COMPOSITES',
  'TECH_STEALTH_TECHNOLOGY'
);
