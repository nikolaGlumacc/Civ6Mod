local function Sample(x, y, width, height)
  local cols = #ROWS[1]
  local nrows = #ROWS
  local by = nrows - math.floor((y / math.max(height - 1, 1)) * (nrows - 1) + 0.5)
  local bx = math.floor((x / math.max(width - 1, 1)) * (cols - 1) + 0.5) + 1
  if by < 1 then by = 1 elseif by > nrows then by = nrows end
  if bx < 1 then bx = 1 elseif bx > cols then bx = cols end
  local row = ROWS[by]
  if not row then return 0 end
  return (string.sub(row, bx, bx) == "1") and 1 or 0
end

local function ell(nx, ny, cx, cy, rx, ry)
  return ((nx - cx) / rx)^2 + ((ny - cy) / ry)^2 <= 1
end

local function IsMountain(x, y, width, height)
  local nx, ny = x / math.max(width - 1, 1), y / math.max(height - 1, 1)
  return ell(nx, ny, 0.18, 0.40, 0.06, 0.025)
      or ell(nx, ny, 0.34, 0.48, 0.09, 0.035)
      or ell(nx, ny, 0.50, 0.50, 0.07, 0.03)
      or ell(nx, ny, 0.40, 0.78, 0.03, 0.10)
      or ell(nx, ny, 0.38, 0.34, 0.02, 0.10)
      or ell(nx, ny, 0.64, 0.34, 0.06, 0.03)
end

local function T(name)
  local r = GameInfo.Terrains[name]
  return r and r.Index or nil
end

function GenerateMap()
  local width, height = Map.GetGridSize()
  if not width or width < 1 then width, height = 100, 60 end
  print("[WW2 Europe] grid " .. width .. "x" .. height)

  local ocean, coast = T("TERRAIN_OCEAN"), T("TERRAIN_COAST")
  local grass = T("TERRAIN_GRASS")
  local grassM = T("TERRAIN_GRASS_MOUNTAIN")
  local plains = T("TERRAIN_PLAINS")
  local desert = T("TERRAIN_DESERT")
  local tundra = T("TERRAIN_TUNDRA")
  local tundraM = T("TERRAIN_TUNDRA_MOUNTAIN")
  local snow = T("TERRAIN_SNOW")
  if not ocean or not grass then print("[WW2 Europe] ERROR"); return end

  local landN = 0
  for y = 0, height - 1 do
    for x = 0, width - 1 do
      local plot = Map.GetPlot(x, y)
      if plot then
        local ny = y / math.max(height - 1, 1)
        local idx = ocean
        if Sample(x, y, width, height) > 0 then
          landN = landN + 1
          if IsMountain(x, y, width, height) then
            idx = (ny > 0.70 and (tundraM or grassM) or (grassM or grass))
          elseif ny < 0.14 then idx = desert or plains or grass
          elseif ny > 0.88 then idx = snow or tundra or grass
          elseif ny > 0.78 then idx = tundra or grass
          elseif ny < 0.32 then idx = plains or grass
          else idx = grass end
        end
        TerrainBuilder.SetTerrainType(plot, idx)
      end
    end
  end
  print("[WW2 Europe] land = " .. tostring(landN))

  if coast then
    for y = 0, height - 1 do
      for x = 0, width - 1 do
        local plot = Map.GetPlot(x, y)
        if plot and plot:IsWater() then
          for dy = -1, 1 do for dx = -1, 1 do
            if not (dx == 0 and dy == 0) then
              local n = Map.GetPlot(x + dx, y + dy)
              if n and not n:IsWater() then TerrainBuilder.SetTerrainType(plot, coast) end
            end
          end end
        end
      end
    end
  end

  pcall(function() AreaBuilder.Recalculate() end)
  pcall(function() TerrainBuilder.AnalyzeChokepoints() end)
  pcall(function() TerrainBuilder.StampContinents() end)
  pcall(function()
    local fg = FeatureGenerator.Create({ rainfall = 2 })
    if fg and fg.AddFeatures then fg:AddFeatures() end
  end)
  pcall(function() AreaBuilder.Recalculate() end)
  pcall(function() ResourceGenerator.Create({ resources = 2 }) end)
  pcall(function()
    AssignStartingPlots.Create({
      MIN_MAJOR_CIV_FERTILITY = 15, MIN_MINOR_CIV_FERTILITY = 5,
      MIN_BARBARIAN_FERTILITY = 1, START_MIN_Y = 2, START_MAX_Y = 2,
      IGNORE_LANDMASS = true, START_CONFIG = 2,
    })
  end)
  print("[WW2 Europe] done")
end
